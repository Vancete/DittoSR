# bluenoise.py: a 64 x 64 blue noise mask by void-and-cluster (Ulichney 1993; toroidal Gaussian energy, sigma 1.5) -
# src/bluenoise64.h (each texel's rank, 0 - 255)
import numpy as np, sys
N, SIG = 64, 1.5
rng = np.random.default_rng(1234)
y, x = np.mgrid[0:N, 0:N]
dx, dy = np.minimum(x, N - x), np.minimum(y, N - y)
K = np.exp(-(dx * dx + dy * dy) / (2 * SIG * SIG))
def energy_add(E, py, px, s): E += s * np.roll(np.roll(K, py, 0), px, 1)
# initial binary pattern: 10 % ones at random, then relaxed (the tightest cluster moved to the largest void)
ones = np.zeros((N, N), bool)
ones.flat[rng.choice(N * N, N * N // 10, replace=False)] = True
E = np.zeros((N, N))
for py, px in zip(*np.nonzero(ones)): energy_add(E, py, px, 1)
while True:
    c = np.argmax(np.where(ones, E, -1e9)); cy, cx = divmod(c, N)
    ones[cy, cx] = False; energy_add(E, cy, cx, -1)
    v = np.argmin(np.where(ones, 1e9, E)); vy, vx = divmod(v, N)
    if (vy, vx) == (cy, cx):
        ones[cy, cx] = True; energy_add(E, cy, cx, 1); break
    ones[vy, vx] = True; energy_add(E, vy, vx, 1)
rank = np.zeros((N, N), int)
init = ones.copy(); Ei = E.copy(); n1 = int(init.sum())
# phase 1: ranks below the initial pattern - remove the tightest clusters
b = init.copy(); Eb = Ei.copy()
for r in range(n1 - 1, -1, -1):
    c = np.argmax(np.where(b, Eb, -1e9)); cy, cx = divmod(c, N)
    b[cy, cx] = False; energy_add(Eb, cy, cx, -1); rank[cy, cx] = r
# phase 2 and 3: ranks above - fill the largest voids
b = init.copy(); Eb = Ei.copy()
for r in range(n1, N * N):
    v = np.argmin(np.where(b, 1e9, Eb)); vy, vx = divmod(v, N)
    b[vy, vx] = True; energy_add(Eb, vy, vx, 1); rank[vy, vx] = r
vals = (rank * 256 // (N * N)).astype(np.uint8)
with open(sys.argv[1], 'w', newline='\n') as f:
    f.write('// Ditto Relight: a 64 x 64 blue noise mask (void-and-cluster, generated by DittoSR\'s own script - no third-party\n')
    f.write('// data): each texel\'s rank, 0 - 255. The main pass\' noise with ao_blue_noise (aomain.hlsl, t8).\n#pragma once\n')
    f.write('static const unsigned char kBlueNoise64[64 * 64] = {\n')
    for i in range(0, N * N, 32): f.write('    ' + ', '.join(str(int(v)) for v in vals.flat[i:i + 32]) + ',\n')
    f.write('};\n')
# a check: the spectrum's low frequencies (blue noise: little energy there)
F = np.abs(np.fft.fft2(vals - vals.mean())) ** 2
lo = F[[1, 1, 2, 0, 0], [0, 1, 0, 1, 2]].mean() / F.mean()
print('done; low-frequency energy / mean %.3f (white noise ~1)' % lo)
